import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';

// Deliberately copy the reviewed private/non-virtual implementation, with an exhaustive patch list.
// The approved mainnet canary (canary-1) was generated from the c4bc022 production source (sha256
// aa3f28c3…cb); its source, diff and approval records stay in the repository history and reports/canary/.
// This generates the LOCAL-ONLY canary-2 candidate from the TapeoutMinerPool/2.1.0 source (84-part split
// with the fixed sink C). It is not approved for any mainnet use.
const original = readFileSync('src/TapeoutMinerPool.sol', 'utf8');
const baseline = '6a2d0c34b42ff97c755843860eb6c9b4353860fa15a08ea582efbe17cc8f5e6d';
if (createHash('sha256').update(original).digest('hex') !== baseline) throw Error('Production source changed; review the adaptation again');
let candidate = original;
function replace(before, after) {
  if (candidate.split(before).length !== 2) throw Error(`Patch is not unique: ${before}`);
  candidate = candidate.replace(before, after);
}
for (const name of ['interfaces/IMining.sol', 'PoolMath.sol', 'TapeoutEntitlementReceipt.sol']) replace(`"./${name}"`, `"../${name}"`);
replace('contract TapeoutMinerPool is Ownable2Step, ReentrancyGuard {', `/// @dev RECOVERABLE CANARY ONLY. Generated by scripts/canary/build-source.mjs.
///      The production notice above describes the copied accounting, not these added permissions.
///      Shutdown is permanent. Claims/sync/releases retain the final composition and histories.
contract RecoverableTapeoutMinerPool is Ownable2Step, ReentrancyGuard {`);
replace('"TapeoutMinerPool/2.1.0"', '"RecoverableTapeoutMinerPool/canary-2-local"');
replace('    string public poolName;', `    address public immutable recoveryController;
    bool public closed;
    mapping(uint256 => bool) public returned;

    error CanaryClosed();
    error CanaryOpen();
    error NotRecoveryController();
    error UnauthorizedCanaryMiner(uint256 id);
    event CanaryShutdown(address indexed controller);
    event CanaryMinerReturned(uint256 indexed id, address indexed destination, bool registered);

    string public poolName;`);
replace('    constructor(Deployment memory d) Ownable(d.owner) {', `    constructor(Deployment memory d) Ownable(d.owner) {
        if (d.depositors.length != 1 || d.depositors[0] != d.owner) revert InvalidDepositors();
        recoveryController = d.owner;`);
replace('        if (active) revert AlreadyActive();', '        if (closed) revert CanaryClosed();\n        if (active) revert AlreadyActive();');
replace('        _requireActive();\n        if (!isDepositor[msg.sender])', '        if (closed) revert CanaryClosed();\n        _requireActive();\n        if (!isDepositor[msg.sender])');
replace('            uint256 id = tokenIds[i];\n            for (uint256 j;', '            uint256 id = tokenIds[i];\n            if (id != 3204 && id != 12485) revert UnauthorizedCanaryMiner(id);\n            for (uint256 j;');
replace('        if (tokenIds.length == 0) revert InvalidBatch();', '        if (closed) revert CanaryClosed();\n        if (tokenIds.length == 0) revert InvalidBatch();');
replace('        uint256 length = _minerIds.length;\n        if (count == 0', '        if (closed) revert CanaryClosed();\n        uint256 length = _minerIds.length;\n        if (count == 0');
replace('    // Internals\n', `    // Canary recovery: NO Mining or BEM calls, no loops, no configurable destination.
    // Keep active/accounting/registry unchanged: already received BEM remains payable by ID/role.
    // If BEM arrived before the interruption, sync/claim/release recognize it at the frozen ratio.
    function shutdown() external {
        if (msg.sender != recoveryController) revert NotRecoveryController();
        if (!closed) {
            closed = true;
            emit CanaryShutdown(msg.sender);
        }
    }

    function emergencyReturn(uint256 id) external nonReentrant {
        if (msg.sender != recoveryController) revert NotRecoveryController();
        if (!closed) revert CanaryOpen();
        if (id != 3204 && id != 12485) revert UnauthorizedCanaryMiner(id);
        address holder = minerCollection.ownerOf(id);
        // Idempotent after an interrupted runner; never touches a miner held by somebody else.
        if (holder == recoveryController) return;
        if (holder != address(this)) revert MinerNotHeld(id, holder);
        minerCollection.transferFrom(address(this), recoveryController, id);
        if (minerCollection.ownerOf(id) != recoveryController) revert MinerNotHeld(id, address(this));
        returned[id] = true;
        emit CanaryMinerReturned(id, recoveryController, _miners[id].registered);
    }

    // Internals
`);
const path = 'src/canary/RecoverableTapeoutMinerPool.sol';
candidate = execFileSync('forge', ['fmt', '-', '--raw'], { input: candidate, encoding: 'utf8' });
mkdirSync('src/canary', { recursive: true });
mkdirSync('reports/canary-local', { recursive: true });
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== candidate) throw Error('Generated canary differs from reviewed patch list');
} else {
  writeFileSync(path, candidate);
  let diff;
  try { diff = execFileSync('diff', ['-u', 'src/TapeoutMinerPool.sol', path], { encoding: 'utf8' }); }
  catch (e) { if (e.status !== 1) throw e; diff = e.stdout; }
  // Never reports/canary/production-canary.diff: that file records the approved canary-1 adaptation.
  writeFileSync('reports/canary-local/production-canary.diff', diff);
}
console.log(`Local canary-2 source matches the exhaustive adaptation of production source sha256 ${baseline}`);
